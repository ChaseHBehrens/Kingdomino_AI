//! Play a game of Kingdomino in the terminal, with any mix of people and bots.
use std::{ fs::OpenOptions, io::Write, sync::Mutex, time::{ Instant, SystemTime, UNIX_EPOCH } };
use inquire::{ MultiSelect, Select, Text, InquireError };
use kingdomino_ai::{
    rng,
    core::{ Board, GameState, Landscape, Ruleset, Turn, game::{ run, Rules } },
    evaluators::evaluator,
    simulation::simulated_deal,
    user_interface::{ human, set_player_names, show_results, user_deal },
};

/// Save every game to LOG_FILE, to study how people play. Each line is one
/// JSON record: the start of a game, a move, or the end of a game.
const LOG_GAMES: bool = false;
const LOG_FILE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/game_log.jsonl");
/// Explains the records, written at the start of each game
const LEGEND: &str = "Dominoes are tile numbers 1-48, the number on the back of the tile. \
    Boards are rows top to bottom separated by '/', each square a letter (W farm (wheat), \
    F field (grassland), T forest, M mine, L lake, S swamp, C castle, . empty) then its crowns. \
    pile is the draw pile in order, null once taken; order is the seats in the order they pick. \
    A move takes `domino` from `pile` at `position` and is option `turn` of `options` as \
    generated by GameState::possible_turns, so games can be replayed. placed lists the new \
    squares as [landscape, crowns, rows up from the castle, columns right of the castle], \
    empty when the domino fits nowhere. boards and scores are from before the move, \
    board is the mover's board after it.";

const HUMAN: &str = "human";
const BOTS: &[&str] = &[
    "claude mce",
    "mce race",
    "mce score",
    "claude",
    "eoh",
    "greedy",
    "random",
];

/// The game being logged
struct Log {
    /// Start time in Unix seconds, identifying the game in every record
    game: u64,
    /// Name and bot of each seat, None for a person
    seats: Vec<(String, Option<String>)>,
    /// Moves logged so far
    moves: usize,
}

static LOG: Mutex<Log> = Mutex::new(Log { game: 0, seats: Vec::new(), moves: 0 });

fn answer<T>(result: Result<T, InquireError>) -> T {
    result.unwrap_or_else(|_| std::process::exit(0))
}

/// Evaluator for a seat: its bot, or the terminal for a person
fn seat_evaluator<const N: usize, const S: usize, R: Ruleset>(
    bot: &Option<String>,
) -> fn(&GameState<N, S, R>, &[Turn]) -> usize {
    match bot {
        Some(bot) => evaluator::<N, S, R>(bot),
        None => human::<N, S, R>,
    }
}

/// `bots[p]` is the bot playing seat p, or None for a person. With `entered`
/// the dominoes drawn are entered at the terminal rather than simulated.
fn play<const N: usize, const S: usize, R: Ruleset>(bots: &[Option<String>], entered: bool) -> Vec<(Board, u32)> {
    let evaluators = std::array::from_fn(|p| {
        if LOG_GAMES { logged::<N, S, R> } else { seat_evaluator::<N, S, R>(&bots[p]) }
    });
    let dealer: fn(u64) -> u8 = if entered { user_deal::<N, S> } else { simulated_deal };
    let results = run::<N, S, R>(dealer, evaluators);
    if LOG_GAMES { log_end(&results); }
    results.to_vec()
}

/// Appends a record to the log straight away, so it survives quitting
fn write(record: String) {
    let file = OpenOptions::new().create(true).append(true).open(LOG_FILE);
    if let Err(e) = file.and_then(|mut f| f.write_all(format!("{record}\n").as_bytes())) {
        eprintln!("Could not write to {LOG_FILE}: {e}");
    }
}

/// A JSON object from keys and JSON values
fn record(fields: &[(&str, String)]) -> String {
    let fields: Vec<String> = fields.iter().map(|(k, v)| format!("\"{k}\":{v}")).collect();
    format!("{{{}}}", fields.join(","))
}

/// A JSON array from JSON values
fn list(items: impl Iterator<Item = String>) -> String {
    format!("[{}]", items.collect::<Vec<_>>().join(","))
}

fn json_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn letter(l: Landscape) -> char {
    match l {
        Landscape::Farm => 'W',
        Landscape::Field => 'F',
        Landscape::Forest => 'T',
        Landscape::Mine => 'M',
        Landscape::Lake => 'L',
        Landscape::Swamp => 'S',
        Landscape::Castle => 'C',
        Landscape::None => '.',
    }
}

/// The board as rows top to bottom, two characters a square
fn board_code(board: &Board) -> String {
    let rows: Vec<String> = (0..5u8).rev().map(|r| {
        (0..5).map(|c| match board.square_landscape(r * 5 + c) {
            Landscape::None => "..".to_string(),
            l => format!("{}{}", letter(l), board.square_crowns(r * 5 + c)),
        }).collect()
    }).collect();
    rows.join("/")
}

/// Squares occupied in `after` but not in `before`, as (landscape, crowns,
/// rows up from the castle, columns right of the castle). Boards shift as
/// kingdoms grow, so squares are matched by where they are from the castle.
fn placed(before: &Board, after: &Board) -> Vec<(char, u8, i32, i32)> {
    let castle = |b: &Board| {
        let sq = (0..25).find(|&sq| b.square_landscape(sq) == Landscape::Castle).unwrap() as i32;
        (sq / 5, sq % 5)
    };
    let ((br, bc), (ar, ac)) = (castle(before), castle(after));
    (0..25u8).filter_map(|sq| {
        let l = after.square_landscape(sq);
        let (dr, dc) = (sq as i32 / 5 - ar, sq as i32 % 5 - ac);
        let (r, c) = (br + dr, bc + dc);
        let was_empty = !(0..5).contains(&r) || !(0..5).contains(&c)
            || before.square_landscape((r * 5 + c) as u8) == Landscape::None;
        (l != Landscape::None && was_empty).then(|| (letter(l), after.square_crowns(sq), dr, dc))
    }).collect()
}

/// Writes the record that starts a game
fn log_start(players: usize, middle: bool, harmony: bool, entered: bool, names: &[String], bots: &[Option<String>]) {
    let game = SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    let seats: Vec<(String, Option<String>)> = names.iter().cloned().zip(bots.iter().cloned()).collect();
    write(record(&[
        ("type", json_str("start")),
        ("game", game.to_string()),
        ("players", players.to_string()),
        ("middle_kingdom", middle.to_string()),
        ("harmony", harmony.to_string()),
        ("dealer", json_str(if entered { "entered" } else { "simulated" })),
        ("seats", list(seats.iter().map(|(name, bot)| record(&[
            ("name", json_str(name)),
            ("player", json_str(bot.as_deref().unwrap_or(HUMAN))),
        ])))),
        ("legend", json_str(LEGEND)),
    ]));
    *LOG.lock().unwrap() = Log { game, seats, moves: 0 };
}

/// Evaluator that plays a seat as usual and logs the move
fn logged<const N: usize, const S: usize, R: Ruleset>(state: &GameState<N, S, R>, turns: &[Turn]) -> usize {
    let seat = state.player_order[0] as usize;
    let (name, bot) = LOG.lock().unwrap().seats[seat].clone();
    let start = Instant::now();
    let choice = seat_evaluator::<N, S, R>(&bot)(state, turns);
    let seconds = start.elapsed().as_secs_f64();

    let turn = turns[choice];
    let dealt = 12 * N - state.deck.count_ones() as usize;
    let mut log = LOG.lock().unwrap();
    log.moves += 1;
    write(record(&[
        ("type", json_str("move")),
        ("game", log.game.to_string()),
        ("move", log.moves.to_string()),
        ("round", (dealt / S).to_string()),
        ("seat", seat.to_string()),
        ("name", json_str(&name)),
        ("player", json_str(bot.as_deref().unwrap_or(HUMAN))),
        ("deck", state.deck.to_string()),
        ("pile", list(state.draw_pile.iter()
            .map(|&d| if d == u8::MAX { "null".to_string() } else { (d + 1).to_string() }))),
        ("order", list(state.player_order.iter().map(|p| p.to_string()))),
        ("boards", list(state.boards.iter().map(|b| json_str(&board_code(b))))),
        ("scores", list((0..N).map(|p| state.score(p).to_string()))),
        ("options", turns.len().to_string()),
        ("turn", choice.to_string()),
        ("position", turn.position.to_string()),
        ("domino", (state.draw_pile[turn.position] + 1).to_string()),
        ("placed", list(placed(&state.boards[seat], &turn.board).into_iter()
            .map(|(l, crowns, r, c)| format!("[\"{l}\",{crowns},{r},{c}]")))),
        ("board", json_str(&board_code(&turn.board))),
        ("seconds", format!("{seconds:.1}")),
    ]));
    choice
}

/// Writes the record that ends a game
fn log_end(results: &[(Board, u32)]) {
    let log = LOG.lock().unwrap();
    let best = results.iter().map(|r| r.1).max().unwrap_or(0);
    write(record(&[
        ("type", json_str("end")),
        ("game", log.game.to_string()),
        ("scores", list(results.iter().map(|r| r.1.to_string()))),
        ("boards", list(results.iter().map(|r| json_str(&board_code(&r.0))))),
        ("winners", list((0..results.len()).filter(|&p| results[p].1 == best).map(|p| json_str(&log.seats[p].0)))),
    ]));
}

fn main() {
    rng::init();

    let players = answer(Select::new("How many players?", vec![2, 3, 4]).with_starting_cursor(2).prompt());
    let bonuses = answer(MultiSelect::new("Bonus rules?", vec!["Middle Kingdom (+10)", "Harmony (+5)"])
        .with_help_message("space to toggle, enter to confirm")
        .raw_prompt());
    let middle = bonuses.iter().any(|b| b.index == 0);
    let harmony = bonuses.iter().any(|b| b.index == 1);
    let entered = answer(Select::new("Dominoes?", vec!["Simulated", "Entered from a real set"]).raw_prompt()).index == 1;

    let mut names: Vec<String> = Vec::new();
    let mut bots: Vec<Option<String>> = Vec::new();
    for p in 1..=players {
        let mut options = vec![HUMAN];
        options.extend_from_slice(BOTS);
        let prompt = format!("Seat {p}{}?", if p == 1 { " (picks first in round 1)" } else { "" });
        let who = answer(Select::new(&prompt, options).prompt());
        if who == HUMAN {
            let name = answer(Text::new("Name?").with_default(&format!("Player {p}")).prompt());
            names.push(name.trim().to_string());
            bots.push(None);
        } else {
            names.push(who.to_string());
            bots.push(Some(who.to_string()));
        }
    }
    if LOG_GAMES { log_start(players, middle, harmony, entered, &names, &bots); }
    set_player_names(names);

    let results = match (players, middle, harmony) {
        (2, false, false) => play::<2, 4, Rules<false, false>>(&bots, entered),
        (2, true, false) => play::<2, 4, Rules<true, false>>(&bots, entered),
        (2, false, true) => play::<2, 4, Rules<false, true>>(&bots, entered),
        (2, true, true) => play::<2, 4, Rules<true, true>>(&bots, entered),
        (3, false, false) => play::<3, 3, Rules<false, false>>(&bots, entered),
        (3, true, false) => play::<3, 3, Rules<true, false>>(&bots, entered),
        (3, false, true) => play::<3, 3, Rules<false, true>>(&bots, entered),
        (3, true, true) => play::<3, 3, Rules<true, true>>(&bots, entered),
        (4, false, false) => play::<4, 4, Rules<false, false>>(&bots, entered),
        (4, true, false) => play::<4, 4, Rules<true, false>>(&bots, entered),
        (4, false, true) => play::<4, 4, Rules<false, true>>(&bots, entered),
        _ => play::<4, 4, Rules<true, true>>(&bots, entered),
    };
    show_results(&results);
}
